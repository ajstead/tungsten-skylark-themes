#!/usr/bin/env python3
"""Generate exports/ts-tokens.css from themes/tokens.json (W3C DTCG format).

Walks the DTCG token tree (ts.color.theme.<id>.{light,dark}.<role>.$value)
and emits the portable CSS custom property sheet (theme blocks + appearance
resolution + WCAG-safe text accents). Verify edits in tokens.json, then
re-run this — never hand-edit the CSS.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TEXT_MIN = 4.5
ACCENT_MIN = 3.0
ROLES = ["bg", "surface", "text", "accent", "accentSoft", "ink"]
ROLE_CSS = {r: r[:6] + r[6].upper() + r[7:] if "_" in r else r for r in ROLES}  # accentSoft -> accentSoft (used with '-' anyway)


def val(node: dict) -> str:
    """$value of a DTCG token node."""
    return node["$value"]


def rel_lum(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    def lin(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = lin(r), lin(g), lin(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(fg: str, bg: str) -> float:
    l1, l2 = rel_lum(fg), rel_lum(bg)
    hi, lo = max(l1, l2), min(l1, l2)
    return (hi + 0.05) / (lo + 0.05)


def wcag_safe_text_accent(palette: dict) -> str | None:
    """Blend the accent toward white or black until it passes AA on bg.

    Direction is chosen by which extreme contrasts more with the bg
    (lighten on dark backgrounds, darken on light ones). Returns the least
    modified candidate that passes, or None if none does.
    """
    def parse(h: str) -> tuple[int, int, int]:
        h = h.lstrip("#")
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)

    r, g, b = parse(palette["accent"])
    toward_white = rel_lum(palette["bg"]) < 0.5

    best: tuple[float, str] | None = None
    for step in range(1, 21):  # blend 5%..100%
        t = step * 0.05
        if toward_white:
            cand = "#{:02X}{:02X}{:02X}".format(
                round(r + (255 - r) * t),
                round(g + (255 - g) * t),
                round(b + (255 - b) * t))
        else:
            cand = "#{:02X}{:02X}{:02X}".format(
                round(r * (1 - t)), round(g * (1 - t)), round(b * (1 - t)))
        if ratio(cand, palette["bg"]) >= TEXT_MIN:
            cand_rgb = parse(cand)
            dist = sum((a - c) ** 2 for a, c in zip((r, g, b), cand_rgb))
            if best is None or dist < best[0]:
                best = (dist, cand)
    return best[1] if best else None


def flat(mode_palette: dict) -> dict:
    """DTCG group {role: {$value}} -> {role: hex}."""
    return {role: val(node) for role, node in mode_palette.items()
            if isinstance(node, dict) and "$value" in node}


def main() -> int:
    tokens = json.loads((ROOT / "themes" / "tokens.json").read_text())
    ext = tokens.get("$extensions", {})
    theme_ids = list(tokens["ts"]["color"]["theme"].keys())

    lines = [
        "/* ===========================================================================",
        "   TUNGSTEN SKYLARK — brand tokens, generated from themes/tokens.json",
        "   (W3C Design Tokens / DTCG format).",
        "   Drop into any web/electron app. Theme = pure variable swap; appearance =",
        "   light/dark variable swap (mirrors the official ts-brand.css mechanics).",
        f"   Discipline: ~10% maximum accent per screen.",
        "   Generated by tools/build-tokens-css.py — regenerate, don't hand-edit.",
        "   ========================================================================== */",
        "",
    ]

    # theme blocks
    for i, tid in enumerate(theme_ids, start=1):
        th = tokens["ts"]["color"]["theme"][tid]
        sel = ":root,\n[data-theme='skylark']" if tid == "skylark" \
            else f"[data-theme='{tid}']"
        lines.append(sel + " {")
        desc = th.get("$description", "")
        lines.append(f"    /* {i} · {desc} */")
        l, d = flat(th["light"]), flat(th["dark"])
        for role in ROLES:
            lr = role.replace("Soft", "-soft")
            lines.append(f"    --th-{lr}-l: {l[role]};"
                         f"{' ' * (10 - len(role))}--th-{lr}-d: {d[role]};")
        lines.append("}")
    lines.append("")

    # working roles + derived + typography + spacing
    fam = tokens["ts"]["font"]["family"]
    display_stack = ", ".join(f"'{f}'" if " " in f else f for f in val(fam["display"]))
    mono_stack = ", ".join(val(fam["mono"]))
    sp = tokens["ts"]["dimension"]["spacing"]
    lines += [
        "/* ---------- working roles (light by default) + derived ---------- */",
        ":root {",
        "    color-scheme: light dark;",
        "    --ts-bg: var(--th-bg-l);",
        "    --ts-surface: var(--th-surface-l);",
        "    --ts-text: var(--th-text-l);",
        "    --ts-accent: var(--th-accent-l);",
        "    --ts-accent-soft: var(--th-accent-soft-l);",
        "    --ts-ink: var(--th-ink-l);",
        "",
        "    --ts-text-soft: color-mix(in srgb, var(--ts-text) 62%, transparent);",
        "    --ts-line: color-mix(in srgb, var(--ts-text) 16%, transparent);",
        "    --ts-line-strong: color-mix(in srgb, var(--ts-text) 30%, transparent);",
        "    --ts-glow: color-mix(in srgb, var(--ts-accent-soft) 24%, transparent);",
        "    --ts-glow-strong: color-mix(in srgb, var(--ts-accent-soft) 42%, transparent);",
        "",
        f"    --font-display: {display_stack};",
        f"    --font-mono: {mono_stack};",
        "",
    ]
    lines.append("    " + " ".join(f"--sp-{k.replace('sp_', '')}: {val(v)};"
                                   for k, v in sp.items()))
    lines += [f"    --radius: {val(tokens['ts']['dimension']['radius'])};",
              f"    --content-max: {val(tokens['ts']['dimension']['contentMax'])};",
              "}", ""]

    # appearance resolution
    def role_assign(mode: str) -> list[str]:
        suffix = "-l" if mode == "light" else "-d"
        out = []
        for r in ROLES:
            lr = r.replace("Soft", "-soft")
            out.append(f"    --ts-{lr}: var(--th-{lr}{suffix});")
        return out

    lines += [
        "html[data-appearance='light'],",
        "[data-theme][data-appearance='light'] {",
        "    color-scheme: light;",
        *role_assign("light"),
        "}",
        "html[data-appearance='dark'],",
        "[data-theme][data-appearance='dark'] {",
        "    color-scheme: dark;",
        *role_assign("dark"),
        "}",
        "@media (prefers-color-scheme: dark) {",
        "    html[data-appearance='auto'],",
        "    html:not([data-appearance]) {",
        "        color-scheme: dark;",
    ]
    lines += [f"        {ln.strip().rstrip(';')};" for ln in role_assign("dark")]
    lines += ["    }", "}", ""]

    # WCAG-safe text accents per theme
    lines += [
        "/* ---------- --ts-accent-text: derived role for text-bearing accent -----",
        "   Explicit sanctioned values (accentText in tokens.json) are used when",
        "   declared; otherwise computed AA-safe blends. NEVER use --ts-accent",
        "   for body-size text. Large text (>=24px / 18.7px bold) may use --ts-accent",
        "   where it holds >=3:1. */",
    ]
    for tid in theme_ids:
        th = tokens["ts"]["color"]["theme"][tid]
        l, d = flat(th["light"]), flat(th["dark"])
        sanctioned_l = val(th["light"]["accentText"]) if "accentText" in th["light"] else None
        sanctioned_d = val(th["dark"]["accentText"]) if "accentText" in th["dark"] else None
        dark_ok = ratio(d["accent"], d["bg"]) >= TEXT_MIN
        light_val = sanctioned_l or (l["accent"] if ratio(l["accent"], l["bg"]) >= TEXT_MIN
                                     else wcag_safe_text_accent(l))
        dark_val = sanctioned_d or (d["accent"] if dark_ok else wcag_safe_text_accent(d))
        if light_val is None or dark_val is None:
            print(f"ERROR: no AA-safe text accent derivable for theme "
                  f"'{tid}'", file=sys.stderr)
            return 1
        lines.append(f"[data-theme='{tid}'] {{")
        lines.append(f"    --ts-accent-text-l: {light_val};   /* on {l['bg']}: {ratio(light_val, l['bg']):.2f}:1 */")
        lines.append(f"    --ts-accent-text-d: {dark_val};   /* on {d['bg']}: {ratio(dark_val, d['bg']):.2f}:1 */")
        lines.append("}")
    lines += [
        ":root { --ts-accent-text: var(--ts-accent-text-l); }",
        "html[data-appearance='dark'] { --ts-accent-text: var(--ts-accent-text-d); }",
        "",
    ]

    out = ROOT / "exports" / "ts-tokens.css"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
