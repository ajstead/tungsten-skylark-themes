#!/usr/bin/env python3
"""Generate exports/ts-tokens.css from themes/tokens.json.

Reads the nine-brand-theme token file and emits the portable CSS custom
property sheet (theme blocks + appearance resolution + WCAG-safe text
accents). Verify edits in tokens.json, then re-run this — never hand-edit
the CSS.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TEXT_MIN = 4.5
ACCENT_MIN = 3.0
ROLES = ["bg", "surface", "text", "accent", "accent_soft", "ink"]


def rel_lum(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    def lin(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = lin(r), lin(g), lin(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(fg: str, bg: str) -> float:
    l1, l2 = rel_lum(fg), rel_lum(bg)
    hi, lo = max(l1, l2), min(l1, l2)
    return (hi + 0.05) / (lo + 0.05)


def wcag_safe_text_accent(palette: dict) -> str | None:
    """Blend the accent toward white or black until it passes AA on bg.

    Direction is chosen by which extreme contrasts more with the bg
    (lighten on dark backgrounds, darken on light ones). Returns the least
    modified candidate that passes, or None if none does.
    """
    def parse(h: str) -> tuple[int, int, int]:
        h = h.lstrip("#")
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)

    r, g, b = parse(palette["accent"])
    br, bg_, bb = parse(palette["bg"])
    toward_white = rel_lum(palette["bg"]) < 0.5

    best: tuple[float, str] | None = None
    for step in range(1, 21):  # blend 5%..100%
        t = step * 0.05
        if toward_white:
            cand = "#{:02X}{:02X}{:02X}".format(
                round(r + (255 - r) * t),
                round(g + (255 - g) * t),
                round(b + (255 - b) * t))
        else:
            cand = "#{:02X}{:02X}{:02X}".format(
                round(r * (1 - t)), round(g * (1 - t)), round(b * (1 - t)))
        if ratio(cand, palette["bg"]) >= TEXT_MIN:
            cand_rgb = parse(cand)
            dist = sum((a - c) ** 2 for a, c in zip((r, g, b), cand_rgb))
            if best is None or dist < best[0]:
                best = (dist, cand)
    return best[1] if best else None


def main() -> int:
    tokens = json.loads((ROOT / "themes" / "tokens.json").read_text())
    lines = [
        "/* ===========================================================================",
        "   TUNGSTEN SKYLARK — brand tokens, generated from themes/tokens.json.",
        "   Drop into any web/electron app. Theme = pure variable swap; appearance =",
        "   light/dark variable swap (mirrors the official ts-brand.css mechanics).",
        "   Discipline: ~10% maximum amber/gold per screen.",
        "   Generated by tools/build-tokens-css.py — regenerate, don't hand-edit.",
        "   ========================================================================== */",
        "",
    ]

    # theme blocks
    for i, th in enumerate(tokens["themes"], start=1):
        sel = ":root,\n[data-theme='skylark']" if th["id"] == "skylark" \
            else f"[data-theme='{th['id']}']"
        lines.append(f"{sel} {{".replace(":root,\n", ":root,\n"))
        lines.append(f"    /* {i} · {th['note']} */")
        l, d = th["light"], th["dark"]
        for role in ROLES:
            lines.append(f"    --th-{role.replace('_', '-')}-l: {l[role]};"
                         f"{' ' * (10 - len(role))}--th-{role.replace('_', '-')}-d: {d[role]};")
        lines.append("}")
    lines.append("")

    # working roles + derived + typography + spacing
    fonts = tokens["typography"]
    sp = tokens["layout"]["spacing"]
    lines += [
        "/* ---------- working roles (light by default) + derived ---------- */",
        ":root {",
        "    color-scheme: light dark;",
        "    --ts-bg: var(--th-bg-l);",
        "    --ts-surface: var(--th-surface-l);",
        "    --ts-text: var(--th-text-l);",
        "    --ts-accent: var(--th-accent-l);",
        "    --ts-accent-soft: var(--th-accent-soft-l);",
        "    --ts-accent-ink: var(--th-ink-l);",
        "",
        "    --ts-text-soft: color-mix(in srgb, var(--ts-text) 62%, transparent);",
        "    --ts-line: color-mix(in srgb, var(--ts-text) 16%, transparent);",
        "    --ts-line-strong: color-mix(in srgb, var(--ts-text) 30%, transparent);",
        "    --ts-glow: color-mix(in srgb, var(--ts-accent-soft) 24%, transparent);",
        "    --ts-glow-strong: color-mix(in srgb, var(--ts-accent-soft) 42%, transparent);",
        "",
        f"    --font-display: {fonts['font_display']};",
        f"    --font-mono: {fonts['font_mono']};",
        "",
    ]
    lines.append("    " + " ".join(f"--sp-{k}: {v}px;" for k, v in sp.items()))
    lines += [f"    --radius: {tokens['layout']['radius']}px;", "}", ""]

    # appearance resolution
    def role_assign(mode: str) -> list[str]:
        suffix = "-l" if mode == "light" else "-d"
        return [f"    --ts-{r.replace('_', '-')}: var(--th-{r.replace('_', '-')}{suffix});"
                for r in ROLES]

    lines += [
        "html[data-appearance='light'],",
        "[data-theme][data-appearance='light'] {",
        "    color-scheme: light;",
        *role_assign("light"),
        "}",
        "html[data-appearance='dark'],",
        "[data-theme][data-appearance='dark'] {",
        "    color-scheme: dark;",
        *role_assign("dark"),
        "}",
        "@media (prefers-color-scheme: dark) {",
        "    html[data-appearance='auto'],",
        "    html:not([data-appearance]) {",
        "        color-scheme: dark;",
    ]
    lines += [f"        {ln.strip()};" if ln.strip().endswith(")") and "--ts" in ln
              else ln.replace("    ", "        ", 1).rstrip(";") + ";"
              for ln in role_assign("dark")]
    lines += ["    }", "}", ""]

    # WCAG-safe text accents per theme
    lines += [
        "/* ---------- WCAG-safe text accents ----------",
        "   Brand accent-l/d can fail AA as *text* on bg; per-theme alternates",
        "   computed by tools/build-tokens-css.py hold >=4.5:1 (dark mode usually",
        "   keeps the brand accent unchanged). */",
    ]
    for th in tokens["themes"]:
        dark_ok = ratio(th["dark"]["accent"], th["dark"]["bg"]) >= TEXT_MIN
        light_safe = wcag_safe_text_accent(th["light"])
        if light_safe is None:
            print(f"ERROR: no AA-safe text accent derivable for theme "
                  f"'{th['id']}' light mode", file=sys.stderr)
            return 1
        d = th["dark"]["accent"] if dark_ok else wcag_safe_text_accent(th["dark"])
        lines.append(f"[data-theme='{th['id']}'] {{")
        lines.append(f"    --ts-accent-text-l: {light_safe};   /* on {th['light']['bg']}: {ratio(light_safe, th['light']['bg']):.2f}:1 */")
        lines.append(f"    --ts-accent-text-d: {d};   /* on {th['dark']['bg']}: {ratio(d, th['dark']['bg']):.2f}:1 */")
        lines.append("}")
    lines += [
        ":root { --ts-accent-text: var(--ts-accent-text-l); }",
        "html[data-appearance='dark'] { --ts-accent-text: var(--ts-accent-text-d); }",
        "",
    ]

    out = ROOT / "exports" / "ts-tokens.css"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
